console.log(10 > 5); // true

console.log(10 < 5); // false

console.log(10 >= 5); // true

console.log(10 <= 5); // false

console.log(10 == 5); // false

console.log(10 != 5); // true

console.log(10 * 2 == 20); // true
console.log(10 * 2 - 5 != 14); // true